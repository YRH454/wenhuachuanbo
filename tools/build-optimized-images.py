"""Build content-addressed display copies; never modify or remove originals."""
import hashlib
import io
import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parent.parent / 'dist'


def read_json(path):
    return json.loads((ROOT / path).read_text(encoding='utf-8'))


def digest(data):
    return hashlib.sha256(data).hexdigest()


def requested_assets():
    assets = {}

    def add(path, edge):
        # Only generate from known files inside dist; candidate portraits are
        # intentionally excluded by collecting only public object and exhibit data.
        resolved = (ROOT / path).resolve(strict=True)
        resolved.relative_to(ROOT.resolve())
        assets[path] = max(assets.get(path, 0), edge)

    manifest = read_json('assembly-manifest.json')
    for city in manifest['cities']:
        for variant in ('A', 'B'):
            add(city['variants'][variant]['src'], 768)
    backgrounds = read_json('city-backgrounds.json')
    add(backgrounds['home']['src'], 1800)
    for entry in backgrounds['cities']:
        if entry.get('status') == 'ready':
            add(entry['src'], 1800)
    for file in sorted((ROOT / 'people-culture-v1/data').glob('[0-9]' * 6 + '.json')):
        data = json.loads(file.read_text(encoding='utf-8'))
        for item in data.get('objects', []):
            media = item.get('media') or {}
            if media.get('kind') in ('ai', 'photo') and media.get('src'):
                add('people-culture-v1/' + media['src'], 1280)
    for file in sorted((ROOT / 'guides').glob('[0-9]' * 6 + '/' + '[0-9]' * 6 + '.json')):
        data = json.loads(file.read_text(encoding='utf-8'))
        for media in data.get('media', []):
            if media.get('src'):
                add('guides/' + data['cityId'] + '/' + media['src'], 1280)
    for record in read_json('museum/artwork-context.json')['records']:
        add('museum/' + record['image'], 1280)
    return sorted(assets.items())


def build(item):
    path, edge = item
    source = ROOT / path
    original = source.read_bytes()
    with Image.open(io.BytesIO(original)) as opened:
        image = ImageOps.exif_transpose(opened)
        image.thumbnail((edge, edge), Image.Resampling.LANCZOS)
        if image.mode not in ('RGB', 'RGBA'):
            image = image.convert('RGBA' if 'transparency' in image.info else 'RGB')
        output = io.BytesIO()
        image.save(output, 'WEBP', quality=85, method=4)
        width, height = image.size
    data = output.getvalue()
    output_hash = digest(data)
    relative = Path(path).parent / 'optimized' / (source.stem + '-' + output_hash[:12] + '.webp')
    target = ROOT / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        if digest(target.read_bytes()) != output_hash:
            raise ValueError('Content-addressed output conflicts with an existing file')
    else:
        target.write_bytes(data)
    return path, {'src': relative.as_posix(), 'sourceSha256': digest(original), 'sha256': output_hash,
                  'width': width, 'height': height, 'sourceBytes': len(original), 'bytes': len(data)}


def main():
    with ThreadPoolExecutor(max_workers=4) as pool:
        entries = dict(pool.map(build, requested_assets()))
    mapping = {path: record['src'] for path, record in entries.items()}
    (ROOT / 'optimized-assets.json').write_text(json.dumps({'version': 1, 'entries': entries}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    module = ('// Generated by tools/build-optimized-images.py. Originals remain available.\n'
              + 'const images = Object.freeze(' + json.dumps(mapping, ensure_ascii=False, separators=(',', ':')) + ');\n'
              + 'export const optimizedAsset = path => images[path] || path;\n')
    (ROOT / 'optimized-assets.mjs').write_text(module, encoding='utf-8', newline='\n')
    home = read_json('city-backgrounds.json')['home']['src']
    css = ('/* Generated by tools/build-optimized-images.py; original remains the fallback. */\n'
           + 'body::before{background-image:image-set(url("' + mapping[home] + '") type("image/webp") 1x,'
           + 'url("' + home + '") type("image/png") 1x)}\n')
    (ROOT / 'optimized-home.css').write_text(css, encoding='utf-8', newline='\n')
    before = sum(entry['sourceBytes'] for entry in entries.values())
    after = sum(entry['bytes'] for entry in entries.values())
    print(f'{len(entries)} display copies: {before / 1048576:.1f} MiB -> {after / 1048576:.1f} MiB')
    print('Home image:', mapping[home])


if __name__ == '__main__':
    main()
